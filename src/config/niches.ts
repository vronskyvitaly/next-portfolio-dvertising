export function getNiches(): NicheType[] {
  const serviceSlugs = new Set(getServices().map(service => service.slug))
  for (const niche of NICHES) {
    if (serviceSlugs.has(niche.slug)) {
      throw new Error(`Слаг ниши «${niche.slug}» совпадает со слагом услуги`)
    }
  }
  return NICHES
}

export function getNiche(slug: string): NicheType | undefined {
  return NICHES.find(niche => niche.slug === slug)
}

/** Базовая услуга ниши — источник цены и срока */
export function getNicheService(niche: NicheType): ServiceType {
  const service = getService(niche.serviceSlug)
  if (!service) {
    throw new Error(
      `Ниша «${niche.slug}» ссылается на несуществующую услугу «${niche.serviceSlug}»`
    )
  }
  return service
}
